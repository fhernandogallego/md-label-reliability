"""Regenera las macros del resumen archivado del piloto SCAYLE.
Los datos por corrida no están incluidos: no se recalcula aquí el bootstrap.
"""
import json
import numpy as np

R=json.load(open('resultados/piloto_scayle.json'))
I=R['intervalos_extremos']
M={'pilN':str(R['n_sistemas']), 'pilRuns':str(R['corridas']),
   'pilRepRatio':f"{R['extremos']['reproducir_vs_original']['razon_mediana']:.2f}"}
for key,name,transform in [('dif_reproducir','RepShift',np.exp),('dif_recocido','RecShift',np.exp),
                           ('sd_dinamica','SdDyn',float),('sd_entre_recocidas','SdRec',float),
                           ('sd_replicas_htpmd','SdHtp',float)]:
    row=I[key]
    for suffix,value in [('',row['valor']),('Lo',row['ic95'][0]),('Hi',row['ic95'][1])]:
        M[f'pil{name}{suffix}']=f'{transform(value):.2f}'
with open('paper/numeros_piloto.tex','w') as f:
    f.write('% Generated by piloto.py from archived summary; pilot bootstrap is not rerun.\n')
    for key,value in M.items():f.write(f'\\newcommand{{\\{key}}}{{{value}}}\n')
print(f"Piloto archivado: {R['corridas']} corridas / {R['n_sistemas']} sistemas; intervalos no recalculados.")
